//! WHIQ: markup the reader doesn't model, kept as opaque pass-through nodes so saving writes it
//! back in place (see `InlineObject::Opaque` for the formats, and `write/passthrough.rs`).
//!
//! - an unknown block-level element (between paragraphs) becomes a `docx-block` object at the
//!   start of the next paragraph (or the end of the story's last one);
//! - an unknown element among a paragraph's runs, or inside a run, becomes a `docx` object;
//! - wrappers the model has no place for (`w:customXml`, `w:smartTag`, `w:bdo`, `w:dir`) keep
//!   their start and end tags as `docx-open` / `docx-close` objects around their content (whole
//!   paragraphs: `docx-block-open` / `docx-block-close`);
//! - unknown run and paragraph properties are kept on the properties (`ext_xml`).
//!
//! An element whose relationships point at parts keeps those parts (and every part they reach)
//! in `Document::passthrough`, as embedded objects do; one that refers to a relationship the
//! package lacks is dropped (writing it back would leave a dangling id).

