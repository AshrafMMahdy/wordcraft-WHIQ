/// Longest kept property markup on one run or paragraph.
const MAX_EXT: usize = 64 * 1024;

pub fn skip_block(name: &str) -> bool {
    BLOCK_SKIP.contains(&name) || name == "?"
}

pub fn skip_inline(name: &str) -> bool {
    INLINE_SKIP.contains(&name)
}

pub fn skip_run_child(name: &str) -> bool {
    RUN_SKIP.contains(&name)
}

/// Whether `e` can be written back at all: its name is in a namespace the parser could name.
fn nameable(e: &El) -> bool {
    !e.name.starts_with("?:") && e.name != "?"
}

/// The unknown run properties of `rpr`, as markup (`None` when there are none).
pub fn rpr_ext(rpr: &El) -> Option<String> {
    let mut s = String::new();
    for k in rpr.els() {
        let known = RPR_KNOWN.contains(&k.name.as_str()) || W14_EFFECTS.contains(&k.name.as_str());
        if !known && nameable(k) {
            s.push_str(&k.to_xml_ext());
        }
    }
    (!s.is_empty() && s.len() <= MAX_EXT).then_some(s)
}

/// The unknown paragraph properties of `ppr`, as markup (`None` when there are none).
pub fn ppr_ext(ppr: &El) -> Option<String> {
    let mut s = String::new();
    for k in ppr.els() {
        if !PPR_KNOWN.contains(&k.name.as_str()) && nameable(k) {
            s.push_str(&k.to_xml_ext());
        }
    }
    (!s.is_empty() && s.len() <= MAX_EXT).then_some(s)
}

/// The canonical prefixes `e` uses (element and attribute names), for its declarations.
fn used_prefixes(e: &El, out: &mut Vec<&'static str>, depth: usize) {
    if depth > MAX_DEPTH {
        return;
    }
    let mut note = |name: &str| {
        if let Some((p, _)) = name.split_once(':')
            && let Some((cp, _)) = NAMESPACES.iter().find(|(x, _)| *x == p)
            && !out.contains(cp)
        {
            out.push(cp);
        }
    };
    note(&e.name);
    for (k, _) in &e.attrs {
        note(k);
    }
    for c in e.els() {
        used_prefixes(c, out, depth + 1);
    }
}

/// `e` as a standalone element: its markup (unknown namespaces kept, see
/// [`El::to_xml_ext`]) with declarations of the known prefixes it uses. `None` when empty or
/// too long.
pub fn standalone(e: &El) -> Option<String> {
    if !nameable(e) {
        return None;
    }
    let xml = e.to_xml_ext();
    if xml.is_empty() || xml.len() > MAX_EMBEDDED_XML {
        return None;
    }
    let mut used = Vec::new();
    used_prefixes(e, &mut used, 0);
    let decls: String =
        used.iter().filter_map(|p| NAMESPACES.iter().find(|(x, _)| x == p)).map(|(p, u)| format!(" xmlns:{p}=\"{}\"", esc(u))).collect();
    let at = xml.find([' ', '/', '>']).unwrap_or(xml.len());
    let mut s = xml;
    s.insert_str(at, &decls);
    Some(s)
}

/// The start and end tags of wrapper `e`, keeping its property children named in `keep` (they
/// come first in it) inside the start: (`<w:customXml …><w:customXmlPr>…</w:customXmlPr>`,
/// `</w:customXml>`).
pub fn wrapper_tags(e: &El, keep: &[&str]) -> Option<(String, String)> {
    if !nameable(e) {
        return None;
    }
    let kids: Vec<Node> = e.els().filter(|c| keep.contains(&c.name.as_str())).cloned().map(Node::El).collect();
    let shell = El { name: e.name.clone(), attrs: e.attrs.clone(), kids };
    let xml = standalone(&shell)?;
    // The written name (an unknown namespace's prefix is rewritten).
    let name: String = xml.get(1..)?.chars().take_while(|c| !matches!(c, ' ' | '/' | '>')).collect();
    let open = if let Some(x) = xml.strip_suffix("/>") { format!("{x}>") } else { xml.strip_suffix(&format!("</{name}>"))?.to_string() };
    Some((open, format!("</{name}>")))
}

impl Reader<'_> {
    /// `e` as an opaque object of `format`, with the parts its relationships reach kept.
    /// `wrap_run`: wrap it in a `w:r` (an unknown child of a run).
    pub(super) fn opaque(&mut self, e: &El, rels: &Rels, format: &str, wrap_run: bool) -> Option<InlineObject> {
        if !nameable(e) {
            return None;
        }
        let wrapped;
        let el = if wrap_run {
            wrapped = El { name: "w:r".into(), attrs: Vec::new(), kids: vec![Node::El(e.clone())] };
            &wrapped
        } else {
            e
        };
        let mut ids = Vec::new();
        super::embed::rel_ids(el, &mut ids, 0)?;
        let mut refs = Vec::new();
        for id in &ids {
            let Some(rel) = rels.by_id(id) else {
                log::warn!("docx: dropping {} (relationship {id} is missing)", e.name);
                return None;
            };
            if !rel.external && !self.keep_part_tree(&rel.target) {
                return None;
            }
            refs.push(EmbeddedRef { id: id.clone(), kind: rel.kind.clone(), target: rel.target.clone(), external: rel.external });
        }
        let xml = standalone(el)?;
        if self.opaque_bytes.saturating_add(xml.len()) > MAX_OPAQUE_TOTAL {
            log::warn!("docx: too much unknown markup; the rest is dropped");
            return None;
        }
        self.opaque_bytes += xml.len();
        Some(InlineObject::Opaque { format: format.into(), xml, text: String::new(), refs })
    }

    /// The section properties of `sect` that aren't modelled, kept with their relationships.
    pub(super) fn section_ext(&mut self, sect: &El, rels: &Rels) -> Option<std::sync::Arc<wordcraft_doc::graphic::Embedded>> {
        let kids: Vec<Node> = sect.els().filter(|k| !SECTPR_KNOWN.contains(&k.name.as_str()) && nameable(k)).cloned().map(Node::El).collect();
        if kids.is_empty() {
            return None;
        }
        let shell = El { name: "w:sectPr".into(), attrs: Vec::new(), kids };
        let Some(InlineObject::Opaque { xml, refs, .. }) = self.opaque(&shell, rels, "docx", false) else { return None };
        Some(std::sync::Arc::new(wordcraft_doc::graphic::Embedded { xml, refs }))
    }

    /// Keep `ac`, the `mc:AlternateContent` `obj` was read from, under the object's fingerprint, so
    /// the object is written back with every branch while it isn't edited.
    pub(super) fn keep_alternate(&mut self, ac: &El, rels: &Rels, obj: &InlineObject) {
        let Some(key) = crate::write::passthrough::fingerprint(&self.doc, obj) else { return };
        let Some(InlineObject::Opaque { xml, refs, .. }) = self.opaque(ac, rels, "docx", false) else { return };
        let bytes = crate::write::passthrough::encode_kept(&xml, &refs);
        self.doc.passthrough.insert(key, std::sync::Arc::new(bytes));
    }

    /// The `docx-open` / `docx-close` objects of an inline wrapper (`w:customXml`, `w:smartTag`,
    /// `w:bdo`, `w:dir`).
    pub(super) fn wrapper_objects(&mut self, e: &El, block: bool) -> Option<(InlineObject, InlineObject)> {
        let keep: &[&str] = &["w:customXmlPr", "w:smartTagPr"];
        let (open, close) = wrapper_tags(e, keep)?;
        self.opaque_bytes += open.len() + close.len();
        let (fo, fc) = if block { ("docx-block-open", "docx-block-close") } else { ("docx-open", "docx-close") };
        let mk = |format: &str, xml: String| InlineObject::Opaque { format: format.into(), xml, text: String::new(), refs: Vec::new() };
        Some((mk(fo, open), mk(fc, close)))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_markup_stands_alone_with_its_namespaces() {
        let x = br#"<w:p xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:f="urn:example:pt"><f:thing f:a="1"><w:t>x</w:t></f:thing></w:p>"#;
        let p = crate::xml::parse(x).unwrap();
        let thing = p.els().next().unwrap();
        let s = standalone(thing).unwrap();
        assert!(s.contains("xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\""), "{s}");
        assert!(s.contains("=\"urn:example:pt\""), "{s}");
        // It parses back to the same names.
        let back = crate::xml::parse(s.as_bytes()).unwrap();
        assert_eq!(back.name, thing.name);
        assert_eq!(back.attrs, thing.attrs);
        let (open, close) = wrapper_tags(thing, &[]).unwrap();
        assert!(open.starts_with("<x") && open.ends_with("\">"), "{open}");
        assert!(close.starts_with("</x") && close.ends_with(":thing>"), "{close}");
    }
}
